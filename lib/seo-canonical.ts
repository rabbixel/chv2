/**
 * Accept Yoast canonicals only when they identify the same public route on
 * the configured storefront origin. Legacy WordPress URLs and cross-route
 * canonicals fall back to the route rendered by this Next.js app.
 */
export function canonicalUrlForPath(
  value: string | undefined,
  siteUrl: string,
  path: string,
): string {
  const fallback = new URL(path, siteUrl);
  if (!value) return fallback.toString();

  try {
    const candidate = new URL(value);
    const candidatePath = candidate.pathname.replace(/\/$/, "") || "/";
    const expectedPath = fallback.pathname.replace(/\/$/, "") || "/";
    if (
      candidate.origin === fallback.origin &&
      candidatePath === expectedPath &&
      !candidate.search &&
      !candidate.hash
    ) {
      return candidate.toString();
    }
  } catch {
    // Invalid imported values use the canonical route generated by the app.
  }

  return fallback.toString();
}
